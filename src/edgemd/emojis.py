def all_emojis() -> tuple[Emoji, ...]:
    """Todos os emojis, na ordem das categorias."""
    return tuple(e for grupo in CATEGORIES.values() for e in grupo)


def by_category(name: str) -> tuple[Emoji, ...]:
    """Emojis de uma categoria; lista vazia se o nome não existir."""
    return CATEGORIES.get(name, ())


def search(query: str, limit: int = 0) -> tuple[Emoji, ...]:
    """Emojis cujo nome ou palavra-chave contenham ``query``.

    A comparação ignora caixa e acento: quem digita "coracao" precisa achar
    "Coração". Um apelido exato (``:tada:``) tem prioridade e vem primeiro.

    ``limit`` maior que zero corta o resultado; o padrão devolve tudo.
    """
    termo = normalize(query.strip().strip(":"))
    if not termo:
        return all_emojis()

    if termo in ALIASES:
        alvo = ALIASES[termo]
        exato = tuple(e for e in all_emojis() if e.char == alvo)
        if exato:
            return exato

    encontrados = tuple(e for e in all_emojis() if termo in e.haystack())
    return encontrados[:limit] if limit > 0 else encontrados


def categories() -> tuple[str, ...]:
    """Nomes das categorias, na ordem do seletor."""
    return tuple(CATEGORIES)
