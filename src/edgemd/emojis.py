"""Catálogo de emojis para o seletor.

Dados, e não dependência. Existem pacotes prontos com os 3.600 emojis do
Unicode e seus nomes oficiais em inglês, mas o que se usa ao escrever uma nota
em português é um conjunto pequeno, e procurar "feliz" ou "coração" precisa
funcionar — o nome oficial é ``grinning face with smiling eyes``.

As palavras-chave são em português, com alguns sinônimos em inglês para quem
digita ``done`` esperando um ✅.
"""

from __future__ import annotations

import unicodedata
from dataclasses import dataclass, field


@dataclass(frozen=True)
class Emoji:
    """Um emoji e como encontrá-lo."""

    char: str
    name: str
    keywords: tuple[str, ...] = field(default_factory=tuple)

    def haystack(self) -> str:
        """Texto normalizado usado na busca."""
        return normalize(" ".join((self.name, *self.keywords)))


def normalize(text: str) -> str:
    """Minúsculas e sem acento, para a busca não depender de digitação exata."""
    decomposto = unicodedata.normalize("NFKD", text.lower())
    return "".join(c for c in decomposto if not unicodedata.combining(c))


